const { JSDOM } = require('jsdom');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const root=require('node:path').resolve(__dirname,'..');
const dom=new JSDOM(fs.readFileSync(root+'/templates/index.html','utf8'),{url:'https://lyric.test',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window;
const calls=[];let copied='';
w.alert=(message)=>{throw Error(message)};
w.scrollTo=()=>{};
w.HTMLElement.prototype.scrollIntoView=()=>{};
w.HTMLMediaElement.prototype.pause=()=>{};
w.HTMLMediaElement.prototype.play=()=>Promise.resolve();
w.navigator.clipboard={writeText:async text=>{copied=text}};
w.fetch=async(url,opts)=>{
 calls.push({url,body:opts?.body && JSON.parse(opts.body)});
 if(url==='/regenerate-line') return {ok:true,json:async()=>({success:true,line:'You left last night'})};
 if(url==='/api/songs/test-song') return {ok:true,json:async()=>({success:true,song:{id:'test-song',title:'Test Song',sections:[{id:'test-section',label:'Hook',type:'hook',lyrics:'You left last night'}]}})};
 return {ok:true,json:async()=>({success:true,songs:[],versions:[]})};
};
w.eval(fs.readFileSync(root+'/static/script.js','utf8'));
(async()=>{
 const version={name:'melodic',label:'Closest to Your Take',lyrics:'I keep moving',score:.8,quality_status:'checked'};
 w.renderResults({phrase_map:[{start_time:.5,end_time:2,syllables:4,target_syllables:4}],flow:{duration:3},listening:{status:'ok',feel:['aching']},versions:[version]});
 const card=w.document.querySelector('.version-card');
 assert.equal(w.getCurrentPhraseIndex(.1),-1);
 assert.equal(w.getCurrentPhraseIndex(1),0);
 assert.equal(w.getCurrentPhraseIndex(2.5),-1);
 await w.regenerateSingleLine(card,'melodic',0);
 assert.equal(card.lyricVersion.lyrics,'You left last night');
 card.querySelector('.copy-btn').click();
 await new Promise(r=>setTimeout(r,0));
 assert.equal(copied,'You left last night');
 await w.loadSong('test-song');
 w.setActiveSection('test-section',false);
 await w.saveVersionToSection(card.lyricVersion,null);
 const save=calls.find(x=>x.url==='/api/songs/test-song/sections/test-section');
 assert.equal(save.body.lyrics,'You left last night');
 assert.equal(save.body.versions[0].lyrics,'You left last night');
 assert.match(w.document.getElementById('performanceSummary').textContent,/aching/);
 w.toggleLockLine(card,'melodic',0);
 w.document.getElementById('regenerateAllBtn').click();
 await new Promise(r=>setTimeout(r,0));
 const regen=calls.find(x=>x.url==='/regenerate-all');
 assert.equal(regen.body.locked_versions.melodic['0'],'You left last night');
 assert.deepEqual(regen.body.flow_data.listening.feel,['aching']);
 const keep=w.createVersionCard(version,true,[{syllables:4}]);
 assert.equal(keep.querySelector('.line-lock-btn').textContent,'🔒');
 console.log('DOM regression checks passed: copy/save state, locks, context, silence gaps, automatic UI.');
 dom.window.close();
})().catch(e=>{console.error(e);dom.window.close();process.exitCode=1;});
